import React, { useState } from 'react';
import { ShieldCheck, KeyRound, AlertCircle, X } from 'lucide-react';
import { useAuthStore } from '../../stores/authStore';

interface MfaModalProps {
  isOpen: boolean;
  onSuccess: () => void;
  onCancel: () => void;
  title?: string;
  description?: string;
}

export const MfaModal: React.FC<MfaModalProps> = ({
  isOpen,
  onSuccess,
  onCancel,
  title = 'Hardware Security MFA Verification',
  description = 'Enter the 6-digit cryptographic TOTP code generated by your air-gapped physical hardware authenticator.',
}) => {
  const [code, setCode] = useState('');
  const [error, setError] = useState<string | null>(null);
  const verifyMfa = useAuthStore((state) => state.verifyMfa);

  if (!isOpen) return null;

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (code.length !== 6) {
      setError('Please provide a valid 6-digit code');
      return;
    }

    const valid = verifyMfa(code);
    if (valid) {
      setError(null);
      setCode('');
      onSuccess();
    } else {
      setError('Invalid or expired MFA token code. Try "123456" for demo.');
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-in fade-in">
      <div className="w-full max-w-md bg-card border border-primary/40 rounded-xl shadow-2xl overflow-hidden p-6 relative">
        <button
          onClick={onCancel}
          className="absolute top-4 right-4 text-muted-foreground hover:text-foreground"
          aria-label="Close"
        >
          <X className="w-5 h-5" />
        </button>

        <div className="flex items-center gap-3 mb-4">
          <div className="p-2.5 bg-primary/20 text-primary rounded-lg border border-primary/40">
            <KeyRound className="w-6 h-6" />
          </div>
          <div>
            <h3 className="text-lg font-bold text-foreground font-mono">{title}</h3>
            <p className="text-xs text-muted-foreground">FIPS 140-3 Hardware Token Shield</p>
          </div>
        </div>

        <p className="text-xs text-muted-foreground mb-6 leading-relaxed">
          {description}
        </p>

        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <label className="block text-xs font-mono font-medium text-foreground mb-1.5">
              6-DIGIT TOTP PASSCODE
            </label>
            <input
              type="text"
              autoFocus
              maxLength={6}
              value={code}
              onChange={(e) => {
                setCode(e.target.value.replace(/\D/g, ''));
                setError(null);
              }}
              placeholder="••••••"
              className="w-full text-center tracking-[0.5em] text-2xl font-mono py-2.5 px-4 bg-background border border-input rounded-md focus:ring-2 focus:ring-primary focus:border-transparent outline-none"
            />
            <p className="text-[11px] text-muted-foreground mt-1 text-center font-mono">
              [Offline Demo Preset: Enter <span className="text-primary font-bold">123456</span>]
            </p>
          </div>

          {error && (
            <div className="flex items-center gap-2 p-2.5 bg-rose-950/40 border border-rose-800 text-rose-300 text-xs rounded">
              <AlertCircle className="w-4 h-4 shrink-0 text-rose-400" />
              <span>{error}</span>
            </div>
          )}

          <div className="flex items-center justify-end gap-3 pt-2">
            <button
              type="button"
              onClick={onCancel}
              className="px-4 py-2 text-xs font-medium text-muted-foreground hover:text-foreground hover:bg-secondary rounded-md transition-colors"
            >
              Cancel
            </button>
            <button
              type="submit"
              className="inline-flex items-center gap-2 px-4 py-2 bg-primary hover:bg-primary/90 text-primary-foreground text-xs font-semibold rounded-md shadow-glow-primary transition-all"
            >
              <ShieldCheck className="w-4 h-4" />
              Verify Token
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
